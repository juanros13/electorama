DECLARE missing text;
BEGIN
  SELECT string_agg(DISTINCT o.year || ' ' || o.office, ', ') INTO missing
    FROM stg_official o
   WHERE NOT EXISTS (SELECT 1 FROM election e WHERE e.year = o.year AND e.office = o.office);
  IF missing IS NOT NULL THEN
    RAISE EXCEPTION 'totales de elecciones que no están en el catálogo: %', missing;
  END IF;
END $$;

