-- =====================================================================
-- Electorama — msvc-electoral-history
-- E2: fuentes, elecciones, boletas, candidaturas y bloques
--
-- Cada elección lleva:
--   · su fuente (url, sha256 de fuentes/manifest.txt y fecha de corte)
--   · TODAS las columnas de votos de su archivo en `ballot_option`, con los
--     partidos que suma cada una. Las combinaciones (PVEM_PT_MORENA, PT_MORENA…)
--     son votos por una coalición marcando varios emblemas.
--   · sus candidaturas: con qué coalición se compitió en cada territorio.
--
-- Las boletas y candidaturas no se capturan a mano, se generan entre los
-- marcadores de abajo:
--   federales (INE)   tools/normalize/ine_catalog.py: del catálogo de
--                     candidaturas; misma persona en un distrito = coalición
--   locales (IEPCT)   tools/normalize/iepct_catalog.py: de las celdas del
--                     archivo por casilla; celda vacía = no estaba en la boleta
--                     de ese territorio, combinación presente = coalición ahí
--   nombres (IEPCT)   tools/normalize/iepct_candidates.py: de las listas de
--                     registro del IEPCT (2021) y de Conóceles (2024); el
--                     IEPCT no publica las de 2018, que se quedan sin nombre
--
-- Bloques (`bloc_party`): la agrupación analítica para comparar entre años
-- aunque cambien las coaliciones. El bloque 4T es decisión del usuario:
--   2018 MORENA + PT + PES      2021 y 2024 MORENA + PT + PVEM
-- El resto sigue las alianzas de oposición de cada año:
--   2018 PAN + PRD + MC (Por México al Frente) y PRI con la oposición; PVEM
--        y NA compitieron solos en Tabasco → OTHERS
--   2021 PAN + PRI + PRD; MC solo; PES, RSP y FXM → OTHERS
--   2024 PAN + PRI + PRD; MC solo
-- Una opción que mezcle bloques cae en OTHERS (E5).
--
-- Es IDEMPOTENTE (upsert por llave natural). Requiere E1.
--
--   psql -U postgres -d msvc_dash_electoral_history -v ON_ERROR_STOP=1 -f E2__elections_catalog.sql
-- =====================================================================

