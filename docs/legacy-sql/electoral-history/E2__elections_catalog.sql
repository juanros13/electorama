-- una etiqueta con un partido que no existe es un error de catálogo
DO $$
DECLARE missing text;
BEGIN
  SELECT string_agg(DISTINCT p, ', ') INTO missing
    FROM (SELECT unnest(party_codes) p FROM stg_option
          UNION SELECT unnest(party_codes) FROM stg_candidacy) x
   WHERE NOT EXISTS (SELECT 1 FROM party WHERE code = p);
  IF missing IS NOT NULL THEN
    RAISE EXCEPTION 'partidos sin catálogo: %', missing;
  END IF;
END $$;

INSERT INTO ballot_option (election_id, raw_label, kind, party_codes, label)
SELECT e.id, o.raw_label, o.kind, o.party_codes, o.label
  FROM stg_option o
  JOIN election e ON e.year = o.year AND e.office = o.office
ON CONFLICT (election_id, raw_label) DO UPDATE
   SET kind = EXCLUDED.kind, party_codes = EXCLUDED.party_codes, label = EXCLUDED.label;

DELETE FROM candidacy c
 USING election e
 WHERE c.election_id = e.id
   AND (e.year, e.office) IN (SELECT DISTINCT year, office FROM stg_candidacy);

INSERT INTO candidacy (election_id, territory, code, name, party_codes)
SELECT e.id, c.territory, c.code, c.name, c.party_codes
  FROM stg_candidacy c
  JOIN election e ON e.year = c.year AND e.office = c.office;

-- quién encabezó cada candidatura local: se casa por territorio y por el
-- mismo conjunto de partidos; el nombre queda como en las federales,
-- "PVEM-MORENA (Nombre)"
UPDATE candidacy c
   SET name = c.name || ' (' || p.person || ')'
  FROM stg_person p
  JOIN election e ON e.year = p.year AND e.office = p.office
 WHERE c.election_id = e.id
   AND c.territory IS NOT DISTINCT FROM p.territory
   AND c.party_codes @> p.party_codes AND c.party_codes <@ p.party_codes
   AND c.name !~ '\)\s*$';

-- verificación: personas registradas cuya candidatura no aparece en la boleta
SELECT p.year, p.office, p.territory, p.party_codes, p.person
  FROM stg_person p
  JOIN election e ON e.year = p.year AND e.office = p.office
 WHERE NOT EXISTS (SELECT 1 FROM candidacy c
                    WHERE c.election_id = e.id
                      AND c.territory IS NOT DISTINCT FROM p.territory
                      AND c.party_codes @> p.party_codes AND c.party_codes <@ p.party_codes)
 ORDER BY 1, 2, p.territory::int NULLS FIRST;

-- y candidaturas locales que se quedaron sin nombre
SELECT e.year, e.office, count(*) AS sin_nombre, string_agg(c.territory || ':' || c.code, ', ' ORDER BY c.territory::int) AS cuales
  FROM candidacy c
  JOIN election e ON e.id = c.election_id
  JOIN source s ON s.id = e.source_id
 WHERE s.publisher = 'IEPCT' AND c.name !~ '\)\s*$'
 GROUP BY 1, 2
 ORDER BY 1, 2;

-- verificación: en cada territorio, ninguna opción cae en dos candidaturas
SELECT e.year, e.office, coalesce(c1.territory, 'estado') AS territorio, o.raw_label,
       c1.code, c2.code
  FROM ballot_option o
  JOIN election e ON e.id = o.election_id
  JOIN candidacy c1 ON c1.election_id = o.election_id AND o.party_codes <@ c1.party_codes
  JOIN candidacy c2 ON c2.election_id = o.election_id AND o.party_codes <@ c2.party_codes
                   AND c2.id > c1.id AND c2.territory IS NOT DISTINCT FROM c1.territory
 WHERE cardinality(o.party_codes) > 0;

SELECT e.year, e.office, count(DISTINCT o.id) AS opciones, count(DISTINCT c.id) AS candidaturas
  FROM election e
  LEFT JOIN ballot_option o ON o.election_id = e.id
  LEFT JOIN candidacy c ON c.election_id = e.id
 GROUP BY 1, 2
 ORDER BY 1, 2;

COMMIT;
